def _old_regime_tax(gross_income: float, deductions: Dict) -> float:
    std_ded   = FinancialConstants.STANDARD_DEDUCTION_OLD
    ded_80c   = min(deductions.get("sec_80c", 0),       FinancialConstants.MAX_80C)
    ded_80d   = min(deductions.get("sec_80d", 0),       FinancialConstants.MAX_80D_SELF + FinancialConstants.MAX_80D_PARENTS)
    nps       = min(deductions.get("nps_80ccd1b", 0),   FinancialConstants.MAX_NPS_80CCD1B)
    hl_int    = min(deductions.get("home_loan_int", 0), FinancialConstants.MAX_HOME_LOAN_INT)
    hra       = deductions.get("hra_exemption", 0)
    other     = deductions.get("other_deductions", 0)

    taxable = max(0, gross_income - std_ded - ded_80c - ded_80d - nps - hl_int - hra - other)

    tax = 0.0
    slabs = [(250_000, 0.0), (250_000, 0.05), (500_000, 0.20), (float("inf"), 0.30)]
    remaining = taxable
    for slab, rate in slabs:
        chunk = min(remaining, slab)
        tax += chunk * rate
        remaining -= chunk
        if remaining <= 0:
            break

    # Surcharge
    if gross_income > 50_00_000:
        tax *= 1.37
    elif gross_income > 10_00_000:
        tax *= 1.15

    # 4% health & education cess
    tax *= 1.04
    return max(0, tax)


def _new_regime_tax(gross_income: float) -> float:
    std_ded = FinancialConstants.STANDARD_DEDUCTION_NEW
    taxable = max(0, gross_income - std_ded)

    tax = 0.0
    slabs = [
        (300_000, 0.0),
        (300_000, 0.05),
        (300_000, 0.10),
        (300_000, 0.15),
        (300_000, 0.20),
        (float("inf"), 0.30),
    ]
    remaining = taxable
    for slab, rate in slabs:
        chunk = min(remaining, slab)
        tax += chunk * rate
        remaining -= chunk
        if remaining <= 0:
            break

    # Rebate u/s 87A (new regime): no tax if taxable ≤ 7L
    if taxable <= 700_000:
        tax = 0.0

    tax *= 1.04  # cess
    return max(0, tax)


def calculate_tax(annual_income: float, deductions: Dict) -> Dict:
    old_tax = _old_regime_tax(annual_income, deductions)
    new_tax = _new_regime_tax(annual_income)

    better = "New Regime" if new_tax <= old_tax else "Old Regime"
    saving = abs(old_tax - new_tax)

    used_80c = min(deductions.get("sec_80c", 0), FinancialConstants.MAX_80C)
    used_80d = min(deductions.get("sec_80d", 0), FinancialConstants.MAX_80D_SELF)
    used_nps = min(deductions.get("nps_80ccd1b", 0), FinancialConstants.MAX_NPS_80CCD1B)

    return {
        "old_regime_tax":       round(old_tax),
        "new_regime_tax":       round(new_tax),
        "better_regime":        better,
        "savings_by_switching": round(saving),
        "effective_rate_old":   (old_tax / annual_income * 100) if annual_income > 0 else 0,
        "effective_rate_new":   (new_tax / annual_income * 100) if annual_income > 0 else 0,
        "80c_gap":              max(0, FinancialConstants.MAX_80C - used_80c),
        "80d_gap":              max(0, FinancialConstants.MAX_80D_SELF - used_80d),
        "nps_gap":              max(0, FinancialConstants.MAX_NPS_80CCD1B - used_nps),
        "total_deduction_gap":  max(0, (FinancialConstants.MAX_80C - used_80c)
                                     + (FinancialConstants.MAX_80D_SELF - used_80d)
                                     + (FinancialConstants.MAX_NPS_80CCD1B - used_nps)),
    }


