class FinancialHealthScorer:
    WEIGHTS = {
        "emergency_fund":   20,
        "savings_rate":     20,
        "retirement":       20,
        "debt":             15,
        "insurance":        15,
        "investment_diversification": 10,
    }

    def score(self, emergency: Dict, income: Dict, retirement: Dict,
              debt: Dict, insurance: Dict, assets: Dict) -> Dict:
        components = {}

        # Emergency fund (0–100)
        ef_pct = emergency["adequacy_percentage"]
        ef_s   = min(100, ef_pct)
        components["emergency_fund"] = {"score": ef_s, "weight": 20, "label": emergency["status"]}

        # Savings rate
        sr = income.get("savings_rate", 0)
        sr_s = min(100, max(0, sr * 5)) if sr >= 0 else 0
        components["savings_rate"] = {
            "score": sr_s, "weight": 20,
            "label": f"{sr:.1f}% (target ≥20%)",
        }

        # Retirement
        ret_s = retirement["readiness_percentage"]
        components["retirement"] = {"score": ret_s, "weight": 20, "label": retirement["status"]}

        # Debt (inverse of DTI)
        dti = debt["debt_to_income_ratio"]
        d_s = max(0, 100 - dti * 2)
        components["debt"] = {"score": d_s, "weight": 15, "label": debt["status"]}

        # Insurance
        monthly_inc = sum(income.get("income", {}).values()) if income else 0
        annual_inc  = monthly_inc * 12
        life_cov    = insurance.get("life_insurance", 0)
        hlth_cov    = insurance.get("health_insurance", 0)
        rec_life    = annual_inc * 10
        rec_health  = 500_000
        ins_life_s  = min(100, (life_cov / rec_life * 100)) if rec_life > 0 else 50
        ins_hlth_s  = min(100, (hlth_cov / rec_health * 100))
        ins_s       = (ins_life_s + ins_hlth_s) / 2
        components["insurance"] = {"score": ins_s, "weight": 15, "label": f"Life: {life_cov/rec_life*100:.0f}% covered" if rec_life > 0 else "N/A"}

        # Diversification
        total_inv = assets.get("total_investments", 0)
        inv_types  = [i for i in assets.get("investments", []) if i["current_value"] > 0]
        div_s      = min(100, len(inv_types) / 3 * 100)
        components["investment_diversification"] = {
            "score": div_s, "weight": 10,
            "label": f"{len(inv_types)} asset classes",
        }

        total_score = sum(
            v["score"] * v["weight"] / 100
            for v in components.values()
        )

        if total_score >= 80:
            cat, desc, col = "Excellent", "Your finances are in great shape. Focus on optimization.", "#00A651"
        elif total_score >= 65:
            cat, desc, col = "Good",      "Solid foundation with specific areas for improvement.",    "#47B86B"
        elif total_score >= 50:
            cat, desc, col = "Fair",      "Functional but with notable gaps that need attention.",    "#F4B400"
        elif total_score >= 35:
            cat, desc, col = "Needs Work","Several critical areas require immediate action.",         "#e08040"
        else:
            cat, desc, col = "Critical",  "Urgent financial attention required across multiple areas.", "#E53E3E"

        return {
            "total_score": round(total_score, 1),
            "category":    cat,
            "description": desc,
            "color":       col,
            "components":  components,
        }


