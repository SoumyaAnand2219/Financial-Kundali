            yp  = np.array(r["yearly_paths"])
            yr  = list(range(yp.shape[1]))
            p5  = np.percentile(yp, 5,  axis=0)
            p50 = np.percentile(yp, 50, axis=0)
            p95 = np.percentile(yp, 95, axis=0)

            fig = go.Figure()
            for path in r["yearly_paths"][:80]:
                fig.add_trace(go.Scatter(x=yr, y=path, mode="lines",
                    line=dict(color=f"rgba(201,168,76,0.06)", width=1), showlegend=False))
            fig.add_trace(go.Scatter(x=yr, y=p5,  mode="lines", line=dict(color=RED,   width=2, dash="dash"), name="5th pct"))
            fig.add_trace(go.Scatter(x=yr, y=p50, mode="lines", line=dict(color=GOLD,  width=3),              name="Median"))
            fig.add_trace(go.Scatter(x=yr, y=p95, mode="lines", line=dict(color=GREEN, width=2, dash="dash"), name="95th pct"))
            if "required_corpus" in r:
                fig.add_hline(y=r["required_corpus"], line_dash="dot", line_color=ORANGE,
                              annotation_text=f"Target {fmt(r['required_corpus'])}", annotation_font_color=ORANGE)
            fig = dark_plotly(fig, 380)
