class RebalancingEngine:
    def analyse(self, investments: List[Dict], risk_level: str) -> Dict:
        targets = FinancialConstants.ALLOCATION_TARGETS.get(risk_level, FinancialConstants.ALLOCATION_TARGETS["moderate"])
        total   = sum(i["current_value"] for i in investments)

        if total == 0:
            return {
                "current_allocation": {"equity": 0, "debt": 0, "gold": 0},
                "target_allocation":  targets,
                "needs_rebalancing":  False,
                "actions":            [],
                "total_portfolio":    0,
            }

        current = {"equity": 0.0, "debt": 0.0, "gold": 0.0}
        for inv in investments:
            t = inv.get("type", "equity")
            if t in current:
                current[t] += inv["current_value"] / total * 100

        actions = []
        needs   = False
        for asset in ["equity", "debt", "gold"]:
            drift = current[asset] - targets[asset]
            if abs(drift) > 5:
                needs  = True
                amount = abs(drift / 100) * total
                actions.append({
                    "asset":       asset.title(),
                    "action":      "SELL" if drift > 0 else "BUY",
                    "amount":      round(amount),
                    "current_pct": round(current[asset], 1),
                    "target_pct":  targets[asset],
                    "drift_pct":   round(drift, 1),
                })

        return {
            "current_allocation": {k: round(v, 1) for k, v in current.items()},
            "target_allocation":  targets,
            "needs_rebalancing":  needs,
            "actions":            actions,
            "total_portfolio":    total,
        }


