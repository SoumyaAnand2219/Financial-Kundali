class GoalPlanner:
    def __init__(self, constants: FinancialConstants):
        self.c = constants

    def plan_goals(self, goals: List[Dict], monthly_surplus: float) -> Dict:
        if not goals:
            return {
                "total_goals": 0, "total_target_amount_pv": 0,
                "total_target_amount_fv": 0, "total_monthly_investment_needed": 0,
                "goals_details": [],
            }

        details = []
        total_pv = total_fv = total_sip = 0

        for g in goals:
            infl   = self.c.GOAL_INFLATION.get(g["type"], self.c.GENERAL_INFLATION)
            pv     = g["target_amount"]
            years  = g["timeframe_years"]
            fv     = pv * (1 + infl) ** years
            saved  = g.get("current_saved", 0)

            # Net FV after growing existing savings
            fv_saved = saved * (1 + self.c.EQUITY_RETURN) ** years
            fv_gap   = max(0, fv - fv_saved)

            r_mo = self.c.EQUITY_RETURN / 12
            n_mo = years * 12
            if r_mo > 0 and n_mo > 0:
                sip_needed = fv_gap / (((1 + r_mo) ** n_mo - 1) / r_mo)
            else:
                sip_needed = fv_gap / max(1, n_mo)

            progress = min(100, saved / pv * 100) if pv > 0 else 100
            year_done = datetime.now().year + years

            if progress >= 100:
                gstatus = "✅ Funded"
            elif sip_needed <= monthly_surplus * 0.5:
                gstatus = "🟡 On Track"
            else:
                gstatus = "🔴 Needs Attention"

            total_pv  += pv
            total_fv  += fv
            total_sip += sip_needed

            details.append({
                "name":                   g["name"],
                "type":                   g["type"],
                "target_amount_pv":       round(pv),
                "target_amount_fv":       round(fv),
                "current_saved":          saved,
                "monthly_saving_needed":  round(sip_needed),
                "timeframe_years":        years,
                "priority":               g.get("priority", "medium"),
                "progress_percentage":    round(progress, 1),
                "inflation_used":         round(infl * 100, 1),
                "completion_year":        year_done,
                "status":                 gstatus,
            })

        return {
            "total_goals":                   len(goals),
            "total_target_amount_pv":        round(total_pv),
            "total_target_amount_fv":        round(total_fv),
            "total_monthly_investment_needed": round(total_sip),
            "goals_details":                 details,
        }


