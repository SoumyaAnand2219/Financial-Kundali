class MonteCarloEngine:
    def __init__(self, n_simulations: int = 1000, seed: int = 42):
        self.n   = n_simulations
        np.random.seed(seed)

    def _monthly_params(self, annual_return: float, annual_vol: float):
        mu  = annual_return / 12
        sig = annual_vol / math.sqrt(12)
        return mu, sig

    def simulate_portfolio(
        self,
        initial_value:    float,
        monthly_contrib:  float,
        years:            int,
        annual_return:    float,
        annual_vol:       float,
        withdrawal_rate:  float = 0.0,
    ) -> Dict:
        months = years * 12
        mu, sig = self._monthly_params(annual_return, annual_vol)

        final_values  = []
        yearly_paths  = []

        for _ in range(self.n):
            val  = initial_value
            path = [val]
            for m in range(months):
                r   = np.random.normal(mu, sig)
                val = val * (1 + r) + monthly_contrib - (val * withdrawal_rate / 12)
                val = max(0, val)
                if (m + 1) % 12 == 0:
                    path.append(val)
            final_values.append(val)
            yearly_paths.append(path)

        fv = np.array(final_values)
        return {
            "statistics": {
                "mean": float(np.mean(fv)),
                "median": float(np.median(fv)),
                "p5":  float(np.percentile(fv,  5)),
                "p25": float(np.percentile(fv, 25)),
                "p50": float(np.percentile(fv, 50)),
                "p75": float(np.percentile(fv, 75)),
                "p95": float(np.percentile(fv, 95)),
                "std": float(np.std(fv)),
            },
            "yearly_paths": yearly_paths,
            "final_values": final_values,
        }

    def retirement_simulation(
        self,
        current_corpus:   float,
        monthly_contrib:  float,
        years_to_retire:  int,
        years_in_retire:  int,
        monthly_expense:  float,
        equity_pct:       float = 0.55,
    ) -> Dict:
        # Blended pre-retirement return
        blend_ret = (equity_pct * FinancialConstants.EQUITY_RETURN
                     + (1 - equity_pct) * FinancialConstants.DEBT_RETURN)
        blend_vol = (equity_pct * FinancialConstants.EQUITY_VOLATILITY
                     + (1 - equity_pct) * FinancialConstants.DEBT_VOLATILITY)

        accum = self.simulate_portfolio(current_corpus, monthly_contrib,
                                        years_to_retire, blend_ret, blend_vol)

        # Required corpus via PV-of-annuity
        r = FinancialConstants.POST_RETIREMENT_RETURN / 12
        n = years_in_retire * 12
        if r > 0:
            pv_factor = (1 - (1 + r) ** (-n)) / r
        else:
            pv_factor = n
        required = monthly_expense * pv_factor

        success  = sum(1 for v in accum["final_values"] if v >= required)
        prob     = success / self.n * 100

        result   = accum.copy()
        result["required_corpus"]        = required
        result["success_probability"]    = prob
        result["success_count"]          = success

        return result

    def goal_simulation(
        self,
        current_saved:   float,
        monthly_sip:     float,
        years:           int,
        target_fv:       float,
        asset_type:      str = "equity",
    ) -> Dict:
        ret_map = {
            "equity": (FinancialConstants.EQUITY_RETURN, FinancialConstants.EQUITY_VOLATILITY),
            "debt":   (FinancialConstants.DEBT_RETURN,   FinancialConstants.DEBT_VOLATILITY),
            "gold":   (FinancialConstants.GOLD_RETURN,   FinancialConstants.GOLD_VOLATILITY),
        }
        ann_ret, ann_vol = ret_map.get(asset_type, ret_map["equity"])
        sim = self.simulate_portfolio(current_saved, monthly_sip, years, ann_ret, ann_vol)
        success = sum(1 for v in sim["final_values"] if v >= target_fv)
        return {
            "success_probability": success / self.n * 100,
            "statistics":          sim["statistics"],
        }


