def run_full_analysis(
    personal_info: Dict,
    income_data:   Dict,
    assets_data:   Dict,
    debts:         List[Dict],
    insurance:     Dict,
    goals:         List[Dict],
    tax_inputs:    Dict,
    risk_score:    int,
) -> Dict:
    constants = FinancialConstants()
    risk_level = personal_info.get("risk_level", "moderate")

    monthly_income   = sum(income_data["income"].values())
    monthly_expenses = income_data["monthly_expenses"]
    savings_rate     = income_data["savings_rate"]
    monthly_surplus  = max(0, monthly_income - monthly_expenses)

    # ── Core modules
    ef_analyser   = EmergencyFundAnalyser()
    ret_planner   = RetirementPlanner(constants)
    debt_analyser = DebtAnalyser()
    goal_planner  = GoalPlanner(constants)
    rebal_engine  = RebalancingEngine()
    scenario_p    = ScenarioPlanner(constants)
    mc_engine     = MonteCarloEngine(n_simulations=1000)
    health_scorer = FinancialHealthScorer()
    rec_engine    = RecommendationEngine()

    # ── Emergency fund
    emergency = ef_analyser.analyse(monthly_expenses, assets_data["cash_and_bank"], debts)

    # ── Retirement
    current_ret_corpus = (assets_data.get("retirement_corpus", 0)
                          + sum(i["current_value"] for i in assets_data.get("investments", [])))
    monthly_inv        = assets_data.get("monthly_investment", 0)

    retirement = ret_planner.plan(
        age             = personal_info["age"],
        retirement_age  = personal_info["retirement_age"],
        life_expectancy = personal_info["life_expectancy"],
        monthly_expense = monthly_expenses,
        current_corpus  = current_ret_corpus,
        monthly_contrib = monthly_inv,
        risk_level      = risk_level,
    )

    # ── Debt
    debt = debt_analyser.analyse(debts, monthly_income)

    # ── Goals
    goals_analysis = goal_planner.plan_goals(goals, monthly_surplus)

    # ── Tax
    annual_income = monthly_income * 12
    tax = calculate_tax(annual_income, tax_inputs or {})

    # ── Rebalancing
    rebalancing = rebal_engine.analyse(assets_data.get("investments", []), risk_level)

    # ── Scenarios
    total_portfolio = assets_data.get("total_investments", 0) + assets_data.get("retirement_corpus", 0)
    scenarios = {
        "job_loss_3m": scenario_p.job_loss(monthly_income, monthly_expenses, assets_data["cash_and_bank"], 3),
        "job_loss_6m": scenario_p.job_loss(monthly_income, monthly_expenses, assets_data["cash_and_bank"], 6),
        "crash_20":    scenario_p.market_crash(total_portfolio, 20, retirement["corpus_needed"]),
        "crash_40":    scenario_p.market_crash(total_portfolio, 40, retirement["corpus_needed"]),
        "early_ret_55": scenario_p.early_retirement(
            personal_info["age"], monthly_expenses,
            current_ret_corpus, monthly_inv, 55, personal_info["life_expectancy"]
        ),
    }

    # ── Monte Carlo
    eq_pct = FinancialConstants.ALLOCATION_TARGETS.get(risk_level, {}).get("equity", 55) / 100
    blend_ret = eq_pct * constants.EQUITY_RETURN + (1 - eq_pct) * constants.DEBT_RETURN
    blend_vol = eq_pct * constants.EQUITY_VOLATILITY + (1 - eq_pct) * constants.DEBT_VOLATILITY

    ret_mc = mc_engine.retirement_simulation(
        current_corpus   = current_ret_corpus,
        monthly_contrib  = monthly_inv,
        years_to_retire  = retirement["years_to_retirement"],
        years_in_retire  = retirement["years_in_retirement"],
        monthly_expense  = retirement["future_monthly_expense"],
        equity_pct       = eq_pct,
    )
    ret_mc["required_corpus"] = retirement["corpus_needed"]

    goal_mc_results = []
    for g in goals:
        infl  = constants.GOAL_INFLATION.get(g["type"], constants.GENERAL_INFLATION)
        fv    = g["target_amount"] * (1 + infl) ** g["timeframe_years"]
        g_det = next((gd for gd in goals_analysis["goals_details"] if gd["name"] == g["name"]), {})
        sip   = g_det.get("monthly_saving_needed", 0)
        gmc   = mc_engine.goal_simulation(
            g.get("current_saved", 0), sip, g["timeframe_years"], fv
        )
        goal_mc_results.append({
            "goal_name":          g["name"],
            "target_amount":      round(fv),
            "success_probability": gmc["success_probability"],
        })

    monte_carlo = {"retirement": ret_mc, "goals": goal_mc_results}

    # ── Health score
    health_score = health_scorer.score(emergency, income_data, retirement, debt, insurance, assets_data)

    # ── Recommendations
    recommendations = rec_engine.generate(
        health_score, emergency, retirement, debt, tax,
        goals_analysis, insurance, rebalancing, assets_data, income_data
    )

    # ── Net worth
    total_liab = debt.get("total_debt", 0)
    total_ass  = (assets_data["cash_and_bank"]
                  + assets_data.get("total_investments", 0)
                  + assets_data.get("retirement_corpus", 0)
                  + assets_data.get("real_estate_value", 0)
                  + assets_data.get("other_assets", 0))
    net_worth  = total_ass - total_liab

    return {
        "health_score":    health_score,
        "emergency":       emergency,
        "retirement":      retirement,
        "debt":            debt,
        "goals":           goals_analysis,
        "tax":             tax,
        "rebalancing":     rebalancing,
        "scenarios":       scenarios,
        "monte_carlo":     monte_carlo,
        "recommendations": recommendations,
        "risk_level":      risk_level,
        "life_stage":      personal_info.get("life_stage", ""),
        "summary": {
            "net_worth":      round(net_worth),
            "annual_income":  round(annual_income),
            "monthly_savings": round(monthly_surplus),
            "savings_rate":   round(savings_rate, 1),
            "total_assets":   round(total_ass),
            "total_liabilities": round(total_liab),
        },
    }

