class ScenarioPlanner:
    def __init__(self, constants: FinancialConstants):
        self.c = constants

    def job_loss(self, monthly_income: float, monthly_expenses: float,
                 emergency_fund: float, months: int) -> Dict:
        total_expenses = monthly_expenses * months
        shortfall      = max(0, total_expenses - emergency_fund)
        covers         = (emergency_fund / monthly_expenses) if monthly_expenses > 0 else 0
        verdict = ("Survivable" if covers >= months
                   else ("Stressful" if covers >= months * 0.5
                         else "Critical"))
        return {
            "scenario":         f"Job Loss for {months} Months",
            "income_lost":      monthly_income * months,
            "emergency_covers": round(covers, 1),
            "fund_shortfall":   round(shortfall),
            "verdict":          verdict,
        }

    def market_crash(self, portfolio_value: float, crash_pct: float,
                     target_corpus: float, recovery_years: int = 3) -> Dict:
        after    = portfolio_value * (1 - crash_pct / 100)
        recovery = after * (1 + self.c.EQUITY_RETURN) ** recovery_years
        gap      = max(0, target_corpus - recovery)
        verdict  = "Resilient" if gap == 0 else "Needs top-up"
        return {
            "scenario":           f"{crash_pct:.0f}% Market Crash",
            "portfolio_after":    round(after),
            "projected_recovery": round(recovery),
            "gap_to_target":      round(gap),
            "verdict":            verdict,
        }

    def early_retirement(self, age: int, monthly_expense: float,
                         current_corpus: float, monthly_contrib: float,
                         target_age: int = 55, life_exp: int = 85) -> Dict:
        ytr       = max(1, target_age - age)
        yir       = max(1, life_exp - target_age)
        r_mo      = self.c.EQUITY_RETURN / 12
        future_exp = monthly_expense * (1 + self.c.POST_RETIREMENT_INFLA) ** ytr
        r_ret_mo  = self.c.POST_RETIREMENT_RETURN / 12
        n         = yir * 12
        pv_f      = (1 - (1 + r_ret_mo) ** (-n)) / r_ret_mo if r_ret_mo > 0 else n
        needed    = future_exp * pv_f
        n_acc     = ytr * 12
        projected = (current_corpus * (1 + r_mo) ** n_acc
                     + monthly_contrib * (((1 + r_mo) ** n_acc - 1) / r_mo)
                       if r_mo > 0 else current_corpus + monthly_contrib * n_acc)
        gap        = max(0, needed - projected)
        extra      = 0.0
        if gap > 0 and r_mo > 0 and n_acc > 0:
            extra = gap / (((1 + r_mo) ** n_acc - 1) / r_mo)
        return {
            "scenario":            f"Early Retirement at {target_age}",
            "corpus_needed":       round(needed),
            "projected_corpus":    round(projected),
            "gap":                 round(gap),
            "feasible":            gap == 0,
            "extra_monthly_needed": round(extra),
        }

    def home_purchase(self, monthly_income: float, current_savings: float,
                      property_value: float, years: int = 5) -> Dict:
        down_pmt  = property_value * 0.20
        loan      = property_value - down_pmt
        rate_mo   = 0.085 / 12          # 8.5% home loan
        tenure_mo = 20 * 12
        if rate_mo > 0:
            emi = loan * rate_mo * (1 + rate_mo) ** tenure_mo / ((1 + rate_mo) ** tenure_mo - 1)
        else:
            emi = loan / tenure_mo
        savings_needed = max(0, down_pmt - current_savings)
        emi_ratio      = (emi / monthly_income * 100) if monthly_income > 0 else 100
        return {
            "property_value":      round(property_value),
            "down_payment":        round(down_pmt),
            "loan_amount":         round(loan),
            "estimated_emi":       round(emi),
            "emi_to_income_pct":   round(emi_ratio, 1),
            "savings_needed":      round(savings_needed),
            "affordable":          emi_ratio <= 40,
        }


