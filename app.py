class DebtAnalyser:
    def analyse(self, debts: List[Dict], monthly_income: float) -> Dict:
        if not debts:
            return {
                "total_debt": 0, "monthly_emi": 0, "debt_to_income_ratio": 0,
                "high_interest_debt_count": 0, "total_interest_payable": 0,
                "status": "Debt-Free", "color": "#00A651",
                "priority_payoff_order": [],
            }

        total_debt = sum(d["outstanding_amount"] for d in debts)
        total_emi  = sum(d.get("emi", 0) for d in debts)
        dti        = (total_emi / monthly_income * 100) if monthly_income > 0 else 0
        hi_count   = sum(1 for d in debts if d.get("interest_rate", 0) >= FinancialConstants.HIGH_INTEREST_THRESHOLD)

        # Total interest payable
        total_int = 0.0
        for d in debts:
            rate     = d.get("interest_rate", 0)
            rem      = d.get("tenure_months_remaining", d.get("tenure_months", 12))
            emi      = d.get("emi", 0)
            total_int += max(0, emi * rem - d["outstanding_amount"])

        if dti <= 20:
            status, color = "Healthy",    "#00A651"
        elif dti <= 40:
            status, color = "Manageable", "#F4B400"
        else:
            status, color = "Stressed",   "#E53E3E"

        sorted_debts = sorted(debts, key=lambda x: x.get("interest_rate", 0), reverse=True)
        priority     = [{"name": d["name"], "rate": d["interest_rate"], "outstanding": d["outstanding_amount"]}
                        for d in sorted_debts]

        return {
            "total_debt":              total_debt,
            "monthly_emi":             total_emi,
            "debt_to_income_ratio":    round(dti, 1),
            "high_interest_debt_count": hi_count,
            "total_interest_payable":  round(total_int),
            "status":                  status,
            "color":                   color,
            "priority_payoff_order":   priority,
        }


