class EmergencyFundAnalyser:
    def analyse(self, monthly_expenses: float, cash_bank: float, debts: List[Dict]) -> Dict:
        target_months = FinancialConstants.EMERGENCY_FUND_MONTHS
        total_emi     = sum(d.get("emi", 0) for d in debts)
        monthly_oblig = monthly_expenses + total_emi
        required      = monthly_oblig * target_months
        pct           = (cash_bank / required * 100) if required > 0 else 100
        months_cov    = (cash_bank / monthly_oblig) if monthly_oblig > 0 else 99

        if pct >= 100:
            status, color = "Adequate", "#00A651"
        elif pct >= 50:
            status, color = "Partial", "#F4B400"
        else:
            status, color = "Insufficient", "#E53E3E"

        return {
            "required_fund":       required,
            "current_fund":        cash_bank,
            "shortfall":           max(0, required - cash_bank),
            "months_coverage":     round(months_cov, 1),
            "adequacy_percentage": min(150, pct),
            "status":              status,
            "color":               color,
            "monthly_obligations": monthly_oblig,
        }


