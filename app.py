class RetirementPlanner:
    def __init__(self, constants: FinancialConstants):
        self.c = constants

    def plan(
        self,
        age:              int,
        retirement_age:   int,
        life_expectancy:  int,
        monthly_expense:  float,
        current_corpus:   float,
        monthly_contrib:  float,
        risk_level:       str = "moderate",
    ) -> Dict:
        ytr       = max(1, retirement_age - age)
        yir       = max(1, life_expectancy - retirement_age)
        eq_pct    = FinancialConstants.ALLOCATION_TARGETS.get(risk_level, {}).get("equity", 55) / 100

        # Future monthly expense (inflation-adjusted)
        future_exp = monthly_expense * (1 + self.c.POST_RETIREMENT_INFLA) ** ytr

        # Corpus needed (PV of annuity in retirement)
        r_mo = self.c.POST_RETIREMENT_RETURN / 12
        n_mo = yir * 12
        if r_mo > 0:
            pv_factor = (1 - (1 + r_mo) ** (-n_mo)) / r_mo
        else:
            pv_factor = n_mo
        corpus_needed = future_exp * pv_factor

        # Projected corpus (deterministic)
        blend = (eq_pct * self.c.EQUITY_RETURN + (1 - eq_pct) * self.c.DEBT_RETURN)
        r_mo_b = blend / 12
        if r_mo_b > 0:
            fv_lump = current_corpus * (1 + r_mo_b) ** (ytr * 12)
            fv_sip  = monthly_contrib * (((1 + r_mo_b) ** (ytr * 12) - 1) / r_mo_b)
        else:
            fv_lump = current_corpus
            fv_sip  = monthly_contrib * ytr * 12
        projected = fv_lump + fv_sip

        readiness = min(100, projected / corpus_needed * 100) if corpus_needed > 0 else 100
        gap        = max(0, corpus_needed - projected)

        # Additional monthly SIP needed to close gap
        extra = 0.0
        if gap > 0 and ytr > 0 and r_mo_b > 0:
            n = ytr * 12
            extra = gap / (((1 + r_mo_b) ** n - 1) / r_mo_b)

        if readiness >= 80:
            status, color = "On Track",    "#00A651"
        elif readiness >= 50:
            status, color = "Needs Work",  "#F4B400"
        else:
            status, color = "Underfunded", "#E53E3E"

        return {
            "years_to_retirement":               ytr,
            "years_in_retirement":               yir,
            "corpus_needed":                     round(corpus_needed),
            "projected_corpus":                  round(projected),
            "readiness_percentage":              round(readiness, 1),
            "gap":                               round(gap),
            "additional_monthly_saving_needed":  round(extra),
            "status":                            status,
            "color":                             color,
            "future_monthly_expense":            round(future_exp),
        }


