def display_monte_carlo(mc: Dict, ret: Dict):
    st.markdown('<div class="section-title">🎲 Monte Carlo Projections</div>', unsafe_allow_html=True)
    st.markdown('<div class="info-box">1,000 simulations using monthly log-normal returns — statistically accurate probability ranges.</div>', unsafe_allow_html=True)

    if "retirement" in mc:
        r = mc["retirement"]
        prob = r.get("success_probability", 0)
        prob_col = GREEN if prob >= 75 else (ORANGE if prob >= 50 else RED)

        c1,c2,c3 = st.columns(3)
